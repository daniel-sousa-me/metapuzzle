"""K4 mating classes for quarter rotation: SAT search on a torus, then cut to tray boards and verify.

Run: python3 experiments/012-constructive-placements/k4.py [COLSxROWS ...]   (needs python-sat)

Model (sides only). Pieces are the cells of placement A on a c x r torus (rotation 0). pi_k is the
side involution of placement k (who touches whom). K4 classes <=> pi_B commutes with pi_A and
pi_C = pi_A pi_B (the Klein four-group acts on every class: {u, pi_A u, pi_B u, pi_C u}).
A placement is a square tiling iff sigma_k = r o pi_k (r = next side of the same piece, clockwise)
has only 4-cycles (four corners around every grid vertex) and the surface is connected; subtour
cuts enforce connectivity. The surfaces of B and C are flat tori with N squares but their period
lattice may differ from A's; each is cut to a rectangle board c' x r' (the lattice must contain
(c', 0)). The tray cut drops the contacts that wrap around. The result is checked with
metapuzzle.connectors on three tray boards (sizes may differ, which the engine allows).
"""
from __future__ import annotations

import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "src"))

from metapuzzle.board import square_board  # noqa: E402
from metapuzzle.connectors import class_summary  # noqa: E402
from metapuzzle.metrics import PAIR_INDEX, shared_adjacencies  # noqa: E402
from metapuzzle.optimize import Solution, validate_solution  # noqa: E402
from metapuzzle.pieces import Piece  # noqa: E402

DELTA = ((0, -1), (1, 0), (0, 1), (-1, 0))


def torus_A(cols, rows):
    N = cols * rows
    step = lambda p, d: ((p // cols + DELTA[d][1]) % rows) * cols + (p % cols + DELTA[d][0]) % cols
    return {(p, d): (step(p, d), (d + 2) % 4) for p in range(N) for d in range(4)}


def develop(N, pi):
    """Components of the square-tiled surface of side involution pi: (pieces, positions, period vectors)."""
    seen, comps = set(), []
    for start in range(N):
        if start in seen:
            continue
        pos = {start: (0, 0, 0)}
        stack, periods = [start], set()
        while stack:
            p = stack.pop()
            x, y, q = pos[p]
            for i in range(4):
                d = (i + q) % 4
                b, j = pi[(p, i)]
                nxt = (x + DELTA[d][0], y + DELTA[d][1], (d + 2 - j) % 4)
                if b in pos:
                    if pos[b] != nxt:
                        periods.add((nxt[0] - pos[b][0], nxt[1] - pos[b][1]))
                else:
                    pos[b] = nxt
                    stack.append(b)
        seen |= set(pos)
        comps.append((sorted(pos), pos, periods))
    return comps


def lattice_basis(vecs):
    """Hermite-style basis ((a, b), (0, d)) of the integer lattice spanned by vecs."""
    from math import gcd
    rows = [list(v) for v in vecs if v != (0, 0)]
    while sum(1 for v in rows if v[0]) > 1:
        rows.sort(key=lambda v: (v[0] == 0, abs(v[0])))
        piv = rows[0]
        rows = [piv] + [[v[0] - (v[0] // piv[0]) * piv[0], v[1] - (v[0] // piv[0]) * piv[1]] if v[0] else v for v in rows[1:]]
    piv = next((v for v in rows if v[0]), [0, 0])
    d = 0
    for v in rows:
        if v is not piv:
            d = gcd(d, v[1])
    a, b = piv
    if a < 0:
        a, b = -a, -b
    return (a, b % d if d else b), (0, d)


def rect_cut(pos, periods, N):
    """Fold developed positions into a c' x r' rectangle (lattice contains (c', 0) or, rotated, (0, r'))."""
    (a, b), (_, d) = lattice_basis(periods)
    # lattice generated by (a, b) and (0, d); index a*d = N. Rows of length: smallest c' with (c',0) in lattice.
    for turn in (0, 1):
        pts = pos if turn == 0 else {p: (-y, x, (q + 1) % 4) for p, (x, y, q) in pos.items()}
        per = periods if turn == 0 else {(-y, x) for x, y in periods}
        (a, b), (_, d) = lattice_basis(per)
        # (c', 0) in lattice: c' = a * (d / gcd(b, d)) ; then rows r' = N / c'
        from math import gcd
        c2 = a * (d // gcd(b, d)) if d else a
        if c2 and N % c2 == 0:
            r2 = N // c2
            # second generator with y = r2: lattice vector (s, r2)
            cells = {}
            for p, (x, y, q) in pts.items():
                # reduce y into [0, r2) using vectors (s, r2): find s from lattice: k*(a,b) + m*(0,d) with y = r2
                cells[p] = (x, y, q)
            shift = next(((k * a, k * b + m * d) for k in range(-N, N + 1) for m in range(-N, N + 1) if k * b + m * d == r2), None)
            if shift is None:
                continue
            out = {}
            for p, (x, y, q) in cells.items():
                k = y // r2
                x2, y2 = x - k * shift[0], y - k * r2
                out[p] = ((y2 % r2) * c2 + x2 % c2, q)
            if len({c for c, _ in out.values()}) == N:
                return c2, r2, out
    return None


def sat_k4(cols, rows, no_shared=False, max_iter=500):
    from pysat.card import CardEnc, EncType
    from pysat.formula import IDPool
    from pysat.solvers import Cadical153
    N = cols * rows
    sides = [(p, i) for p in range(N) for i in range(4)]
    piA = torus_A(cols, rows)
    r = lambda u: (u[0], (u[1] + 1) % 4)
    pool, s = IDPool(), Cadical153()
    M = {}
    for u in sides:
        for v in sides:
            if u < v and len({u[0], v[0], piA[u][0], piA[v][0]}) == 4:
                M[u, v] = M[v, u] = pool.id(("m",) + u + v)
    part = {u: [v for v in sides if (u, v) in M] for u in sides}
    for u in sides:
        for cl in CardEnc.equals([M[u, v] for v in part[u]], 1, vpool=pool, encoding=EncType.seqcounter).clauses:
            s.add_clause(cl)
        for v in part[u]:
            if u < v:
                s.add_clause([-M[u, v], M[piA[u], piA[v]]])
    for tag, post in (("B", lambda v: v), ("C", lambda v: piA[v])):
        S2 = {}
        for u in sides:
            for v in part[u]:
                y = r(post(v))
                for v2 in part[y]:
                    w = r(post(v2))
                    if w == u:
                        s.add_clause([-M[u, v], -M[y, v2]])
                        continue
                    key = (u, w)
                    if key not in S2:
                        S2[key] = pool.id(("s2", tag) + u + w)
                    s.add_clause([-M[u, v], -M[y, v2], S2[key]])
        rowsS = {}
        for (u, w), var in S2.items():
            rowsS.setdefault(u, []).append(var)
        for vs in rowsS.values():
            for cl in CardEnc.atmost(vs, 1, vpool=pool, encoding=EncType.seqcounter).clauses:
                s.add_clause(cl)
        for (u, w), var in list(S2.items()):
            s.add_clause([-var, S2[(w, u)]] if (w, u) in S2 else [-var])
    if no_shared:
        adjA = {frozenset((p, piA[(p, d)][0])) for p in range(N) for d in range(4)}
        for (u, v), m in M.items():
            if u < v and (frozenset((u[0], v[0])) in adjA or frozenset((u[0], piA[v][0])) in adjA):
                s.add_clause([-m])
    for it in range(max_iter):
        if not s.solve():
            return None
        model = set(x for x in s.get_model() if x > 0)
        piB = {u: v for (u, v), var in M.items() if var in model}
        piC = {u: piA[v] for u, v in piB.items()}
        cuts = 0
        for pi, post in ((piB, lambda v: v), (piC, lambda v: piA[v])):
            comps = develop(N, pi)
            if len(comps) > 1:
                for pieces, _, _ in comps:
                    P = set(pieces)
                    s.add_clause([M[u, v] for u in sides if u[0] in P for v in part[u] if post(v)[0] not in P])
                    cuts += 1
        if not cuts:
            return piA, piB, piC
    return None


def torus_check(piA, piB, piC):
    """Every class {u, A u, B u, C u} has 4 sides on 4 pieces and the three matchings are its 1-factorization."""
    ok = True
    for u in piA:
        cls = {u, piA[u], piB[u], piC[u]}
        if len(cls) != 4 or len({x[0] for x in cls}) != 4:
            ok = False
        if piB[piA[u]] != piA[piB[u]]:
            ok = False
    return ok


def tray_solution(cols, rows, piA, piB, piC):
    N = cols * rows
    boards, placements = [square_board(cols, rows, "tray", "quarter")], [{p: (p, 0) for p in range(N)}]
    for pi in (piB, piC):
        (_, pos, per), = develop(N, pi)
        cut = rect_cut(pos, per, N)
        if cut is None:
            return None
        c2, r2, pl = cut
        boards.append(square_board(c2, r2, "tray", "quarter"))
        placements.append({p: (c, 90 * q) for p, (c, q) in pl.items()})
    pieces = [Piece(p, "interior", "any", frozenset({0, 90, 180, 270}), None, ("andro",) * 4) for p in range(N)]
    return Solution(boards, pieces, placements)


def main():
    for arg in sys.argv[1:] or ["4x4"]:
        c, r = map(int, arg.split("x"))
        t0 = time.time()
        res = sat_k4(c, r)
        if res is None:
            print(f"{arg}: no connected K4 scheme found ({time.time() - t0:.0f}s)")
            continue
        piA, piB, piC = res
        sol = tray_solution(c, r, piA, piB, piC)
        print(f"{arg}: torus K4 check {'OK' if torus_check(piA, piB, piC) else 'FAILED'} ({time.time() - t0:.0f}s); "
              f"boards " + ", ".join(f"{b.cols}x{b.rows}" for b in sol.boards))
        s = class_summary(sol)
        shared = [shared_adjacencies(sol.placements[i], sol.placements[j], sol.boards[i], sol.boards[j])[0] for i, j in PAIR_INDEX]
        sizes = sorted({row["size"] for row in s["per_class"]})
        print(f"  tray cut: valid {not validate_solution(sol)}, sides {s['sides']}, classes {s['classes']}, sizes {sizes}, "
              f"complete K4 {sum(1 for row in s['per_class'] if row['size'] == 4 and row['false'] == 0)}, "
              f"false fits {s['false_fits']} (ratio {s['false_ratio']:.3f}), shared {shared}")
        for k, b in enumerate(sol.boards):
            grid = [["" for _ in range(b.cols)] for _ in range(b.rows)]
            for p, (cell, rot) in sol.placements[k].items():
                grid[cell // b.cols][cell % b.cols] = f"{p:2d}@{rot:<3d}"
            print(f"  placement {'ABC'[k]}:")
            for row in grid:
                print("    " + " ".join(row))


if __name__ == "__main__":
    main()
