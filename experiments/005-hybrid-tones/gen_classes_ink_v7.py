"""Ink version of classes-v7.json (experiment 005): march_line outlines on white.

Reuses the converter of gen_classes_ink.py (plain tiers white, transitions a march_line outline of their
mask, motifs a black rim with a white body). Every v7 transition, including the new g, t, b and n classes,
is a march_mask with its own mask, so it gets the same march_line outline. Writes classes-ink-v7.json only
after it validates.

Run: python3 experiments/005-hybrid-tones/gen_classes_ink_v7.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parents[1] / "src"))

from metapuzzle.classes import ClassSpec  # noqa: E402

import gen_classes_ink as ink  # noqa: E402

SRC = HERE / "classes-v7.json"
OUT = HERE / "classes-ink-v7.json"


def main() -> None:
    v7 = json.loads(SRC.read_text(encoding="utf-8"))
    classes = {name: ink.convert(src) for name, src in v7["classes"].items()}
    spec = {
        "_note": ("Ink version of classes-v7.json, generated by gen_classes_ink_v7.py; do not edit by hand. "
                  "Plain tiers white; every transition (including diag g, tip t, bump b, notch n) is a "
                  "march_line outline of its mask; motifs a black rim with a white body."),
        "ref_size": v7.get("ref_size", 100),
        "palette": ink.PALETTE,
        "classes": classes,
    }
    ClassSpec.from_dict(spec).validate()          # raises before anything is written
    OUT.write_text(json.dumps(spec, indent=2) + "\n", encoding="utf-8")
    new = sum(1 for n in classes if len(n) == 3 and n[2] in "gtbn")
    print(f"wrote {OUT.name} with {len(classes)} classes (new diag/tip/bump/notch: {new})")


if __name__ == "__main__":
    main()
