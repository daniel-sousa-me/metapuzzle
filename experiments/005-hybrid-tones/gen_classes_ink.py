"""Ink version of classes-v4.json: black lines on white, for studying shape and piece mapping.

Run ``python3 experiments/005-hybrid-tones/gen_classes_ink.py``. It reads ``classes-v4.json``
and writes ``classes-ink.json`` only after the result validates.

Per class kind:
* Plain tiers (no mask, no motif: D, M, L, S, W): a white background, nothing else. The
  background is a ``stipple`` with density 0, so no new primitive is needed for a fill.
* Transitions (every class with a ``march_mask``): a white background plus one
  ``march_line`` layer with ``outline_of`` the class's mask. The line uses the mask's
  seed and geometry, so it lies exactly on the boundary of the full-colour piece.
* Motifs (SUN, FLO, FLB, CLD, LEF, MOON): a white background, a black copy of the motif
  scaled up by ``2 * STROKE`` (so the black rim is ``STROKE * size`` wide, as the lines
  are), and a white copy on top with black details. ``motif`` has no outline-only mode,
  so the outline is this rim. Both copies use ``jitter 0``, because each layer draws its
  own seeded jitter, and the copies would not line up otherwise.
  CLD's ``fleck`` is drawn at 92% opacity, so its interior is a faint grey.

The six transition classes DM, DL, MD, ML, LD, LM are the v3 scene codes. Each is the
v4 class of the same letters with a straight edge (``DMs`` and so on). Rotations are as in v4.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "src"))

from metapuzzle.classes import ClassSpec  # noqa: E402

SRC = HERE / "classes-v4.json"
OUT = HERE / "classes-ink.json"
STROKE = 0.035                     # line width as a fraction of size (march_line's default)
PALETTE = {"white": "#ffffff", "black": "#000000"}
PLAIN_BG = {"primitive": "stipple", "palette": ["white"], "params": {"density": 0}, "background": True}
LINE_COLORS = ["white", "black"]   # march_line strokes palette[1]
MOTIF_OUTLINE = ["white", "black", "white"]   # motif fills palette[1] black; details in white
MOTIF_BODY = ["black", "white", "black"]      # motif fills palette[1] white; details in black
V3_CODES = {"DM": "DMs", "DL": "DLs", "MD": "MDs", "ML": "MLs", "LD": "LDs", "LM": "LMs"}


def _rotations(src: dict) -> dict:
    out = {"directional": src.get("directional", False)}
    if "allowed_rotations" in src:
        out["allowed_rotations"] = src["allowed_rotations"]
    return out


def plain(src: dict) -> dict:
    return {"layers": [dict(PLAIN_BG)], **_rotations(src)}


def transition(src: dict) -> tuple[dict, dict]:
    """(ink class, the mask it needs). The mask is copied so the outline finds its seed."""
    if len(src["masks"]) != 1:
        raise SystemExit(f"expected one mask, got {sorted(src['masks'])}")
    (name, mask), = src["masks"].items()
    if mask["primitive"] != "march_mask":
        raise SystemExit(f"mask {name!r} is {mask['primitive']}, not march_mask")
    line = {"primitive": "march_line", "palette": LINE_COLORS, "params": {"stroke": STROKE},
            "outline_of": name, "background": False}
    return {"layers": [dict(PLAIN_BG), line], "masks": {name: dict(mask)}, **_rotations(src)}, name


def motif(src: dict) -> dict:
    layers = [layer for layer in src["layers"] if layer["primitive"] == "motif"]
    top = layers[-1]                       # the topmost motif layer is the shape
    p = top["params"]
    if p.get("rotation", "none") != "none" or p.get("halo", 0.0):
        raise SystemExit("ink motif needs rotation none and no halo, so both copies align")
    scale = float(p.get("scale", 0.5))
    shape = {k: v for k, v in p.items() if k not in ("scale", "jitter", "color_index", "halo_color_index")}
    rim = {"primitive": "motif", "palette": MOTIF_OUTLINE, "background": False,
           "params": {**shape, "scale": round(scale + 2 * STROKE, 4), "jitter": 0.0}}
    body = {"primitive": "motif", "palette": MOTIF_BODY, "background": False,
            "params": {**shape, "scale": scale, "jitter": 0.0}}
    return {"layers": [dict(PLAIN_BG), rim, body], **_rotations(src)}


def convert(src: dict) -> dict:
    if src.get("masks"):
        return transition(src)[0]
    if any(layer["primitive"] == "motif" for layer in src["layers"]):
        return motif(src)
    return plain(src)


def main() -> None:
    v4 = json.loads(SRC.read_text(encoding="utf-8"))
    classes = {name: convert(src) for name, src in v4["classes"].items()}
    for code, source in V3_CODES.items():
        classes[code] = convert(v4["classes"][source])
    spec = {
        "_note": ("Ink version of classes-v4.json, generated by gen_classes_ink.py; do not edit "
                  "by hand. Plain tiers are white, transitions are a march_line outline of their "
                  "edge, motifs are a black rim with a white body. DM DL MD ML LD LM are the v3 "
                  "scene codes (straight edges). See the script for details."),
        "ref_size": v4.get("ref_size", 100),
        "palette": PALETTE,
        "classes": classes,
    }
    ClassSpec.from_dict(spec).validate()          # raises before anything is written
    OUT.write_text(json.dumps(spec, indent=2) + "\n", encoding="utf-8")
    kinds = {"plain": 0, "transition": 0, "motif": 0}
    for name, c in classes.items():
        kinds["transition" if "masks" in c else "motif" if any(
            layer["primitive"] == "motif" for layer in c["layers"]) else "plain"] += 1
    print(f"wrote {OUT} with {len(classes)} classes: {kinds}")


if __name__ == "__main__":
    main()
