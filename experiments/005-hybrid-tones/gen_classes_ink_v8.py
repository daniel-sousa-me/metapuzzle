"""Ink version of classes-v8.json (experiment 005): march_line outlines on white.

The v7 classes are converted exactly as in gen_classes_ink_v7.py (through gen_classes_ink.convert).
A tee junction is converted here: a white base, and one march_line of the whole internal outline
(part 0: all three arms), drawn in black with the same geometry as its two masks, so the ink
matches the painted junction. Writes classes-ink-v8.json only after it validates.

Run: python3 experiments/005-hybrid-tones/gen_classes_ink_v8.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parents[1] / "src"))

from metapuzzle.classes import ClassSpec  # noqa: E402

import gen_classes_ink as ink  # noqa: E402

SRC = HERE / "classes-v8.json"
OUT = HERE / "classes-ink-v8.json"
STROKE = 0.035   # the stroke width of the v7 outlines


def junction_ink(src: dict) -> dict:
    """White base, and the junction's internal outline as one black march_line.

    The line outlines a part-0 mask (all three arms) that shares the seed group of the tee
    parts, so for every piece it lies exactly on the boundaries of the painted masks.
    """
    tee = src["masks"]["p1"]
    params = {**tee["params"], "part": 0}
    return {
        "layers": [
            {"primitive": "stipple", "palette": ["white"], "params": {"density": 0},
             "background": True},
            {"primitive": "march_line", "palette": ["white", "black"],
             "params": {"stroke": STROKE}, "outline_of": "p0", "background": False},
        ],
        "masks": {"p0": {"primitive": "march_mask", "seed_group": tee["seed_group"],
                         "params": params}},
        "directional": False,
        "allowed_rotations": list(src["allowed_rotations"]),
    }


def main() -> None:
    v8 = json.loads(SRC.read_text(encoding="utf-8"))
    classes = {}
    for name, src in v8["classes"].items():
        is_junction = "p1" in src.get("masks", {})
        classes[name] = junction_ink(src) if is_junction else ink.convert(src)
    spec = {
        "_note": ("Ink version of classes-v8.json, generated by gen_classes_ink_v8.py; do not edit by "
                  "hand. The v7 classes as in classes-ink-v7.json. Each <A><B><C>j tee is a white base "
                  "and one black march_line of its internal outline (part 0, the same geometry as its "
                  "masks)."),
        "ref_size": v8.get("ref_size", 100),
        "palette": ink.PALETTE,
        "classes": classes,
    }
    ClassSpec.from_dict(spec).validate()          # raises before anything is written
    OUT.write_text(json.dumps(spec, indent=2) + "\n", encoding="utf-8")
    junctions = [n for n in classes if "p1" in v8["classes"][n].get("masks", {})]
    print(f"wrote {OUT.name} with {len(classes)} classes ({len(junctions)} junctions: "
          f"{' '.join(junctions)})")


if __name__ == "__main__":
    main()
